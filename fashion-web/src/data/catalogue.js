import datasetItems from './dataset_items.json';
import externalItems from './external_datasets.json';

// Merged outfits: Hand-curated + Kaggle Clothes Dataset + Global Fashion Datasets (100+ outfits)
export const ALL_OUTFITS = [...OUTFITS, ...datasetItems, ...externalItems];

export const OCCASIONS = ["Any", ...new Set(ALL_OUTFITS.map(o => o.occasion))].sort((a, b) => a === "Any" ? -1 : b === "Any" ? 1 : a.localeCompare(b));
export const SEASONS   = ["Any", ...new Set(ALL_OUTFITS.map(o => o.season))].sort((a, b) => a === "Any" ? -1 : b === "Any" ? 1 : a.localeCompare(b));
export const STYLES    = ["Any", ...new Set(ALL_OUTFITS.map(o => o.style))].sort((a, b) => a === "Any" ? -1 : b === "Any" ? 1 : a.localeCompare(b));

export function getRecommendations(occasion, season, style) {
  return ALL_OUTFITS.filter(o =>
    (occasion === "Any" || o.occasion === occasion) &&
    (season   === "Any" || o.season   === season)   &&
    (style    === "Any" || o.style    === style)
  );
}

export function getRandomOutfits(count = 9) {
  const shuffled = [...ALL_OUTFITS].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
